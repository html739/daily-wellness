CREATE TABLE WELLNESS_DAILY_RECORDS (
    RECORD_DATE DATE PRIMARY KEY,
    HABIT_1 CHAR(1),
    HABIT_2 CHAR(1),
    HABIT_3 CHAR(1),
    HABIT_4 CHAR(1),
    HABIT_5 CHAR(1),
    HABIT_6 CHAR(1),
    WATER_GLASSES NUMBER(1),
    MOOD VARCHAR2(20),
    SLEEP_HOURS NUMBER(4,1),
    ACTIVITY_MINUTES NUMBER(4),
    UPDATED_AT DATE DEFAULT SYSDATE
);

CREATE OR REPLACE PROCEDURE SAVE_WELLNESS_RECORD (
    P_RECORD_DATE IN DATE,
    P_HABIT_1 IN CHAR,
    P_HABIT_2 IN CHAR,
    P_HABIT_3 IN CHAR,
    P_HABIT_4 IN CHAR,
    P_HABIT_5 IN CHAR,
    P_HABIT_6 IN CHAR,
    P_WATER IN NUMBER,
    P_MOOD IN VARCHAR2,
    P_SLEEP IN NUMBER,
    P_ACTIVITY IN NUMBER
)
AS
BEGIN
    MERGE INTO WELLNESS_DAILY_RECORDS T
    USING (
        SELECT P_RECORD_DATE AS RECORD_DATE FROM DUAL
    ) S
    ON (T.RECORD_DATE = S.RECORD_DATE)

    WHEN MATCHED THEN
        UPDATE SET
            T.HABIT_1 = P_HABIT_1,
            T.HABIT_2 = P_HABIT_2,
            T.HABIT_3 = P_HABIT_3,
            T.HABIT_4 = P_HABIT_4,
            T.HABIT_5 = P_HABIT_5,
            T.HABIT_6 = P_HABIT_6,
            T.WATER_GLASSES = P_WATER,
            T.MOOD = P_MOOD,
            T.SLEEP_HOURS = P_SLEEP,
            T.ACTIVITY_MINUTES = P_ACTIVITY,
            T.UPDATED_AT = SYSDATE

    WHEN NOT MATCHED THEN
        INSERT (
            RECORD_DATE, HABIT_1, HABIT_2, HABIT_3,
            HABIT_4, HABIT_5, HABIT_6,
            WATER_GLASSES, MOOD, SLEEP_HOURS, ACTIVITY_MINUTES
        )
        VALUES (
            P_RECORD_DATE, P_HABIT_1, P_HABIT_2, P_HABIT_3,
            P_HABIT_4, P_HABIT_5, P_HABIT_6,
            P_WATER, P_MOOD, P_SLEEP, P_ACTIVITY
        );

    COMMIT;
END;

